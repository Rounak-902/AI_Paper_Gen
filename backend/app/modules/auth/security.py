# Access tokens — doc 07 §7.1
# ---------------------------------------------------------------------------
def create_access_token(
    *,
    user_id: uuid.UUID,
    active_org_id: Optional[uuid.UUID],
    role: Optional[str],
    session_id: str,
    settings: Settings,
    now: Optional[_dt.datetime] = None,
) -> str:
    """Mint a signed access token carrying doc 07 §7.1's payload.

    ``activeOrgId`` and ``role`` are nullable. That follows from this task's decision to
    make ``orgId`` optional at login: a user who has not yet chosen an organization has
    no active org and therefore no role within one. Such a token authenticates
    (``get_current_user`` succeeds) but does not authorize (``get_org_context`` returns
    403 on ``requested_org_id is None``, exactly as P1-T6 already proved). Doc 08 lines
    934-938's ``/select-org`` flow re-mints with the org filled in, and that re-mint is
    P1-T8's endpoint calling this function.

    ``iat``/``exp`` are UTC-aware datetimes; PyJWT converts them to NumericDate itself.
    Passing naive datetimes here would have them interpreted as local time and produce
    tokens that expire hours early or late depending on the server's timezone.
    """
    issued = now or _dt.datetime.now(_dt.timezone.utc)
    expires = issued + _dt.timedelta(minutes=settings.JWT_ACCESS_EXPIRY_MINUTES)

    payload: dict[str, Any] = {
        "userId": str(user_id),
        "activeOrgId": str(active_org_id) if active_org_id else None,
        "role": role,
        "sid": session_id,
        "typ": ACCESS_TOKEN_TYPE,
        "iat": issued,
        "exp": expires,
    }
    return jwt.encode(payload, settings.JWT_SECRET, algorithm=settings.JWT_ALGORITHM)


def decode_access_token(token: str, settings: Settings) -> AccessTokenClaims:
    """Verify a token's signature and claims, or raise :class:`InvalidToken`.

    The security-critical line is ``algorithms=[settings.JWT_ALGORITHM]``. PyJWT
    requires the allow-list, and passing a single-element list is what makes the
    ``alg: "none"`` attack impossible: a token whose header says ``none`` (or ``RS256``,
    the key-confusion variant) does not match the allow-list and is rejected before any
    claim is read. This is precisely the gap ``frontend/lib/mock-auth.ts`` has, and the
    reason this task's brief calls it out — a shape check on a decoded payload would
    accept an unsigned token that looks perfect.

    ``verify_signature`` and ``verify_exp`` are also set explicitly rather than relying
    on PyJWT's defaults, for the same reason ``type=Type.ID`` is explicit above: a
    security property that depends on a library default is undefended against an
    upgrade.
    """
    if not token:
        raise InvalidToken("empty token")

    try:
        payload = jwt.decode(
            token,
            settings.JWT_SECRET,
            algorithms=[settings.JWT_ALGORITHM],
            options={
                "require": list(REQUIRED_CLAIMS),
                "verify_signature": True,
                "verify_exp": True,
                "verify_iat": True,
            },
        )
    except jwt.ExpiredSignatureError as exc:
        raise TokenExpired("expired") from exc
    except jwt.InvalidAlgorithmError as exc:
        raise InvalidToken("algorithm not allowed") from exc
    except jwt.MissingRequiredClaimError as exc:
        raise InvalidToken(f"missing claim {exc.claim}") from exc
    except jwt.InvalidTokenError as exc:
        # Covers bad signature, malformed segments, bad iat — every remaining PyJWT
        # failure derives from this. Caught last so the narrower cases above keep their
        # specific server-side reason.
        raise InvalidToken(f"invalid: {type(exc).__name__}") from exc

    if payload.get("typ") != ACCESS_TOKEN_TYPE:
        # A refresh credential presented as a bearer token. Doc 07 §7.1 gives the
        # refresh token a different representation entirely (opaque UUID, not a JWT), so
        # this branch is defence in depth rather than the primary separation — but it is
        # the branch that keeps holding if that representation ever changes.
        raise InvalidToken(f"wrong token type {payload.get('typ')!r}")

    try:
        user_id = uuid.UUID(str(payload["userId"]))
    except (ValueError, TypeError, KeyError) as exc:
        raise InvalidToken("userId is not a uuid") from exc

    raw_org = payload.get("activeOrgId")
    active_org_id: Optional[uuid.UUID] = None
    if raw_org not in (None, "", "null"):
        try:
            active_org_id = uuid.UUID(str(raw_org))
        except (ValueError, TypeError) as exc:
            # Not treated as "no org": a malformed org claim in a *signed* token means
            # the token was minted wrong, and silently downgrading it to org-less would
            # convert a minting bug into a confusing 403 much further downstream.
            raise InvalidToken("activeOrgId is not a uuid") from exc

    role = payload.get("role")
    if role is not None and not isinstance(role, str):
        raise InvalidToken("role is not a string")

    session_id = payload.get("sid")
    if not isinstance(session_id, str) or not session_id:
        raise InvalidToken("sid is missing or not a string")

    return AccessTokenClaims(
        user_id=user_id,
        active_org_id=active_org_id,
        role=role,
        session_id=session_id,
        issued_at=_dt.datetime.fromtimestamp(payload["iat"], tz=_dt.timezone.utc),
        expires_at=_dt.datetime.fromtimestamp(payload["exp"], tz=_dt.timezone.utc),
    )


