"""Password hashing and access-token cryptography — doc 07 §7.2 and §7.1 (P1-T7).

This module is the *only* place in the codebase that touches a plaintext password or a
signing secret. Everything above it deals in hashes and tokens.

Doc 07 §7.2, verbatim
---------------------
    Algorithm: Argon2id
    Salt: Per-user, generated by the library
    Parameters: Tuned for ~250ms on target hardware
    Storage: users.password_hash (nullable — NULL for OAuth/SSO-only accounts)

REPORTED GAP — hashing parameters. Doc 07 gives a *latency target* ("~250ms on target
hardware"), not m/t/p values, and does not name the target hardware. It is therefore
impossible to satisfy the doc literally at authoring time; the number depends on the
machine. Resolution used here, in priority order:

1. ``app/core/config.py`` already pins ``ARGON_MEMORY_COST=65536`` (64 MiB),
   ``ARGON_TIME_COST=3``, ``ARGON_PARALLELISM=4``. Config that already exists beats a
   value invented here, and these are also argon2-cffi's own library defaults.
2. Those values clear the OWASP Password Storage Cheat Sheet's Argon2id minimum
   (m=19456 / t=2 / p=1) with room to spare on every axis.
3. Because the doc's requirement is a *measurement*, the verification harness measures
   the real hash time on the actual machine and prints it. If it lands far from 250ms,
   the fix is to retune the three config values — not to change this module.

The parameters are read from settings on every call site through a cached hasher, so
retuning is a config change and a restart, never a code change.

Doc 07 §7.1, verbatim
---------------------
    Access Token (JWT, signed, ~15 min TTL)
      Payload: { userId, activeOrgId, role, iat, exp }

REPORTED ADDITION — two claims beyond that list. ``typ`` and ``sid`` are added, and the
doc's payload list is explicit enough that additions have to be justified rather than
assumed:

* ``typ: "access"`` exists because §7.1 defines two credentials and §7.5 requires the
  refresh token never be accepted as an access credential. Without a type claim, the
  only thing separating them is that one happens to be a UUID — a distinction that
  disappears the moment someone changes the refresh-token representation. Verification
  rejects any token whose ``typ`` is not exactly ``access``.
* ``sid`` (session id) exists because §7.5 requires rejecting **revoked** tokens. A
  stateless JWT cannot be revoked; something in it has to name the session whose
  revocation can be looked up. ``sid`` is the refresh-token family id from §7.3, so
  "revoke entire session family" and "reject revoked access tokens" become the same
  fact.
"""

from __future__ import annotations

import asyncio
import datetime as _dt
import logging
import uuid
import weakref
from dataclasses import dataclass
from typing import Any, Final, Optional

import jwt
from anyio import CapacityLimiter, to_thread
from argon2 import PasswordHasher, Type
from argon2.exceptions import InvalidHash, VerificationError, VerifyMismatchError

from app.core.config import Settings

logger = logging.getLogger("papergen.auth.security")

#: The ``typ`` claim value that marks a token as usable as an access credential.
ACCESS_TOKEN_TYPE: Final[str] = "access"

#: Claims that must be present for a token to be considered structurally valid. PyJWT
#: enforces this list itself via ``options={"require": ...}``, so a token missing
#: ``exp`` is rejected by the library rather than by a later ``if`` that someone could
#: delete.
#:
#: ``activeOrgId`` and ``role`` are both absent on purpose: both are nullable (see
#: :func:`create_access_token`), and requiring either would make a valid org-less token
#: undecodable instead of merely unauthorized. What makes this a hazard rather than a
#: style preference is that **PyJWT's require check tests ``payload.get(claim) is
#: None``** — so a claim that *is* present, carrying ``null``, counts as missing.
#: :func:`create_access_token` always emits ``"role": role``, so an org-less token
#: carries ``"role": null``.
#:
#: P1-T8 FIX. ``role`` was listed here until P1-T8's tenancy suite added the first routes
#: reachable with an org-less token (``GET /orgs``, ``POST /orgs``,
#: ``POST /auth/switch-org``) and every one of them returned 401 ``missing claim role``
#: before ``get_current_user`` ran. The effect was never confined to tests:
#: ``app/modules/auth/service.py``'s ``login`` sets ``role = None`` whenever the caller
#: names no ``orgId``, and ``refresh`` re-mints from the stored session role, so a
#: multi-org user could not reach ``POST /auth/switch-org`` — the one route that would
#: have issued them an org-scoped token. Doc 08 lines 934-938's ``/select-org`` flow was
#: unreachable, with no recovery but logging in again and naming an org.
#:
#: Removing it does not weaken authorization, which is why it is the correct fix rather
#: than a convenient one: ``app/common/deps.py``'s ``get_current_user`` maps a falsy role
#: to ``roles=()``, and ``get_org_context`` refuses on ``requested_org_id is None`` and
#: again on an empty role set. A roleless token therefore authenticates and does not
#: authorize — 403, not 401 — which is exactly what this module's own docstrings,
#: ``service.py``'s, and ``deps.py``'s all already described.
REQUIRED_CLAIMS: Final[tuple[str, ...]] = ("userId", "sid", "typ", "iat", "exp")

#: A syntactically valid Argon2id hash of a throwaway value, used by
#: :func:`dummy_verify` to equalise the timing of the user-not-found path. Generated
#: once at import from a random secret so it is not a fixed string in the binary.
_DUMMY_HASH: Optional[str] = None


class InvalidToken(Exception):
    """A token failed cryptographic or structural verification.

    Local to this module and deliberately *not* an ``AppError``. This module has no
    opinion about HTTP; mapping to 401 is ``get_current_user``'s job, and keeping the
    mapping there means every rejection reason funnels through the one place that
    already produces an identical client-visible message.
    """


class TokenExpired(InvalidToken):
    """The signature was valid but ``exp`` has passed.

    A subclass so that a caller which only wants "reject this" needs one ``except``,
    while a caller that wants to answer "should the client try refreshing?" can
    distinguish it. That distinction is sanctioned rather than invented: doc 01's error
    catalogue has EH-15 "Session expired" and ``app/common/errors.py`` documents that
    callers meaning expiry pass ``eh_ref="EH-15"`` explicitly. The client-visible
    *message* stays identical either way — only ``ehRef`` differs, which is what lets a
    frontend decide to refresh instead of redirecting to login.
    """


@dataclass(frozen=True, slots=True)
class AccessTokenClaims:
    """The verified contents of an access token.

    Frozen because a verified claim set must not be mutable after the fact — a later
    ``claims.role = "super_admin"`` would be a privilege escalation that type-checks.
    """

    user_id: uuid.UUID
    active_org_id: Optional[uuid.UUID]
    role: Optional[str]
    session_id: str
    issued_at: _dt.datetime
    expires_at: _dt.datetime


# ---------------------------------------------------------------------------
# Argon2id — doc 07 §7.2
# ---------------------------------------------------------------------------
def build_hasher(settings: Settings) -> PasswordHasher:
    """Construct the Argon2id hasher from settings.

    ``type=Type.ID`` is passed explicitly. argon2-cffi's default already *is* Argon2id,
    but doc 07 §7.2 names the variant as a requirement, and a requirement that is
    satisfied only by a library default is one library upgrade away from being violated
    silently. Argon2i and Argon2d are both wrong here — id is the hybrid that resists
    both side-channel and GPU-tradeoff attacks, which is why it is the variant every
    current guideline names.
    """
    return PasswordHasher(
        time_cost=settings.ARGON_TIME_COST,
        memory_cost=settings.ARGON_MEMORY_COST,
        parallelism=settings.ARGON_PARALLELISM,
        type=Type.ID,
    )


_hasher_cache: dict[tuple[int, int, int], PasswordHasher] = {}


def get_hasher(settings: Settings) -> PasswordHasher:
    """Cached hasher keyed on the three cost parameters.

    Cached because ``PasswordHasher`` construction is cheap but not free and login is a
    hot path; keyed on the parameters so that a settings change (a test overriding cost
    downward, a retune after measurement) produces a different hasher instead of
    silently reusing the old one.
    """
    key = (settings.ARGON_TIME_COST, settings.ARGON_MEMORY_COST, settings.ARGON_PARALLELISM)
    hasher = _hasher_cache.get(key)
    if hasher is None:
        hasher = build_hasher(settings)
        _hasher_cache[key] = hasher
    return hasher


def hash_password(password: str, settings: Settings) -> str:
    """Hash a plaintext password, returning a PHC-format Argon2id string.

    The return value carries the variant, the parameters and the per-user salt inside
    it (``$argon2id$v=19$m=65536,t=3,p=4$<salt>$<hash>``), which is what makes
    :func:`password_needs_rehash` possible without a schema change to record what
    parameters each row was hashed with.

    The plaintext is never logged, and it is never returned. Note there is no
    ``log.debug`` of the input anywhere in this module — doc 07 §19.4 requires "no
    secrets, tokens, or PII reach the logs", and a debug line is exactly how that rule
    gets broken in practice.
    """
    return get_hasher(settings).hash(password)


def verify_password(password: str, stored_hash: Optional[str], settings: Settings) -> bool:
    """Verify a plaintext against a stored hash. Never raises for a wrong password.

    Comparison is performed inside argon2-cffi (``PasswordHasher.verify`` →
    ``argon2_verify`` in the C binding), which compares the derived key in constant
    time. There is no ``==`` on a secret anywhere in this module; a Python string
    comparison short-circuits on the first differing byte and leaks the match length.

    ``stored_hash is None`` returns False rather than raising: doc 07 §7.2 makes
    ``users.password_hash`` nullable for "OAuth/SSO-only accounts", so a password login
    against such an account is a legitimate failed attempt, not an error.
    """
    if not stored_hash:
        return False
    try:
        return bool(get_hasher(settings).verify(stored_hash, password))
    except VerifyMismatchError:
        # The ordinary wrong-password case.
        return False
    except (VerificationError, InvalidHash):
        # A corrupt or foreign hash in the column. Logged because it means bad data,
        # not a bad password — but still a failed verification for the caller.
        logger.error("password_hash_unusable reason=%s", "invalid_or_corrupt_hash")
        return False


def password_needs_rehash(stored_hash: str, settings: Settings) -> bool:
    """True when a stored hash was made with weaker parameters than current settings.

    Exposed so that the login path can upgrade a hash transparently after a successful
    verification — the only moment the plaintext is available to rehash with. Doc 07
    does not require this; it is the standard companion to a "tuned parameters" policy,
    because retuning is worthless if existing rows keep their old cost forever.
    """
    try:
        return bool(get_hasher(settings).check_needs_rehash(stored_hash))
    except InvalidHash:
        return False


def dummy_verify(settings: Settings) -> None:
    """Burn one Argon2id verification against a throwaway hash.

    Called on the user-not-found branch of login. Without it, a missing email answers
    in microseconds while a wrong password takes ~250ms by design, and that difference
    is a remotely measurable account-existence oracle — which would defeat doc 07
    §20.4's "Generic error messages that do not reveal whether an email exists" while
    the error *message* stayed perfectly generic.
    """
    global _DUMMY_HASH
    hasher = get_hasher(settings)
    if _DUMMY_HASH is None:
        _DUMMY_HASH = hasher.hash(uuid.uuid4().hex)
    try:
        hasher.verify(_DUMMY_HASH, "not-the-password")
    except Exception:  # noqa: BLE001 - the point is the elapsed time, not the result
        pass


# ---------------------------------------------------------------------------
# Async wrappers — why the three functions above must never be awaited directly
# ---------------------------------------------------------------------------
# Argon2id is *deliberately* expensive: doc 07 §7.2's "~250ms" target means each hash or
# verification is a quarter-second of memory-hard CPU work inside a C extension. Called
# straight from an ``async def``, that work runs **on the event loop**, and because it is
# C code holding the GIL it is not merely slow — nothing else in the process makes any
# progress for its duration. Ten concurrent logins would serialise into 2.5 seconds
# during which every unrelated request, health check and database callback is frozen. The
# password policy would have become an availability defect.
#
# So every plaintext-touching call is offloaded to a worker thread. This is safe for the
# usual reason C extensions are: argon2-cffi releases the GIL for the actual computation,
# so threads here give real parallelism rather than just non-blocking behaviour.
#
# The concurrency cap is the second half of the fix and matters as much as the offload.
# anyio's default thread limiter allows 40 concurrent tasks; at 64 MiB each that is
# ~2.5 GiB of resident memory reachable by 40 unauthenticated POSTs. The limiter below
# bounds it at 4 (~256 MiB), which is also roughly the point where added concurrency stops
# helping on a 4-core box. This bounds *memory*, not request rate — it is not a substitute
# for the login rate limiting deferred out of this task (see the package docstring), and
# under load it converts that gap from a memory-exhaustion vector into a queueing one.
_HASH_CONCURRENCY: Final[int] = 4

#: Keyed by event loop, weakly, rather than a single module-level limiter. An anyio
#: primitive is bound to the loop that created it, and reusing one across loops raises at
#: runtime — which is exactly what a test suite that spins up a fresh loop per test would
#: do. The weak keys mean a finished loop's limiter is collected with it.
_hash_limiters: "weakref.WeakKeyDictionary[asyncio.AbstractEventLoop, CapacityLimiter]" = (
    weakref.WeakKeyDictionary()
)


def _hash_limiter() -> CapacityLimiter:
    loop = asyncio.get_running_loop()
    limiter = _hash_limiters.get(loop)
    if limiter is None:
        limiter = CapacityLimiter(_HASH_CONCURRENCY)
        _hash_limiters[loop] = limiter
    return limiter


async def hash_password_async(password: str, settings: Settings) -> str:
    """:func:`hash_password`, off the event loop. Use this from any ``async def``."""
    return await to_thread.run_sync(
        hash_password, password, settings, limiter=_hash_limiter()
    )


async def verify_password_async(
    password: str, stored_hash: Optional[str], settings: Settings
) -> bool:
    """:func:`verify_password`, off the event loop. Use this from any ``async def``."""
    return await to_thread.run_sync(
        verify_password, password, stored_hash, settings, limiter=_hash_limiter()
    )


async def dummy_verify_async(settings: Settings) -> None:
    """:func:`dummy_verify`, off the event loop.

    Offloaded through the *same* limiter as the real verification on purpose. If the
    not-found path were unbounded while the found path queued behind a limiter, the queue
    wait itself would restore the account-existence oracle that :func:`dummy_verify`
    exists to close — a real password check would be measurably slower under load than a
    nonexistent one.
    """
    await to_thread.run_sync(dummy_verify, settings, limiter=_hash_limiter())


